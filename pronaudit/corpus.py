_SENT_SPLIT = re.compile(r"(?<=[.?!])\s+")


def from_text_files(paths: list[Path]) -> list[Item]:
    """실제 운용 스크립트를 문장 단위로 잘라 문항으로 만든다."""
    items: list[Item] = []
    for p in paths:
        if not p.exists():
            continue
        raw = p.read_text(encoding="utf-8").strip().strip('"')
        for k, sent in enumerate(s.strip() for s in _SENT_SPLIT.split(raw)):
            if not normalize(sent):
                continue
            items.append(Item(
                id=f"file:{p.stem}:{k:03d}", text=sent, expect=[sent],
                axis="실문장", mode="domain", sensitivity="low",
                note=f"{p.name} 문장 {k}",
            ))
    return items


def _variants(word: str, id_prefix: str, axis: str, group: str, note: str,
              include_carrier: bool, sensitivity: str) -> list[Item]:
    """낱말 하나를 단독 + 캐리어 두 자리로 펼친다."""
    nw = word in NONWORDS
    out = [Item(id=f"{id_prefix}:{word}:bare", text=word, expect=[word], axis=axis,
                group=group, mode="bare", note=note, target=word,
                sensitivity=sensitivity, nonword=nw)]
    if include_carrier:
        for mode, tpl in CARRIERS.items():
            out.append(Item(id=f"{id_prefix}:{word}:{mode}", text=tpl.format(word),
                            expect=[tpl.format(word)], axis=axis, group=group,
                            mode=mode, note=note, target=word,
                            sensitivity=sensitivity, nonword=nw))
    return out


def build(include_carrier: bool = True, extra_files: list[Path] | None = None,
          include_nonword: bool = False) -> list[Item]:
    items: list[Item] = []

    for a, b, axis, note in PAIRS:
        gid = f"{a}|{b}"
        for w in (a, b):
            if w in NONWORDS and not include_nonword:
                continue
            items.extend(_variants(w, f"pair:{gid}", axis, gid, note,
                                   include_carrier, "high"))

    for w, axis, note in PHONOLOGY:
        items.extend(_variants(w, "phon", axis, "", note, include_carrier, "low"))

    for src, oks, axis in READINGS:
        items.append(Item(id=f"read:{src}", text=src, expect=oks, axis=axis,
                          mode="bare", note="읽기 규칙"))

    for w in DOMAIN_WORDS:
        items.extend(_variants(w, "word", "도메인낱말", "", "", include_carrier, "high"))

    for k, s in enumerate(DOMAIN_SENTENCES):
        items.append(Item(id=f"sent:{k:02d}", text=s, expect=[s],
                          axis="도메인문장", mode="domain", sensitivity="low"))

    if extra_files:
        items.extend(from_text_files(extra_files))

    return items


