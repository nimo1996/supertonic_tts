# ── 캐리어 문장 ───────────────────────────────────────────────────────────────
# 낱말 단독(bare)은 짧은 발화 경로(short_candidates)를, 캐리어는 실제 문장
# 조건을 각각 재려고 둘 다 돌린다. 캐리어 앞부분을 고정해야 대상 낱말의
# 운율 위치가 문항마다 같아진다.
# 캐리어를 둘 두는 이유: 파일럿에서 낱말 단독("하함")은 TTS가 제대로 읽어도
# whisper가 매번 "하하"로 적었다 — 짧고 드문 낱말은 STT의 언어모델 사전확률이
# 음향을 이겨서, 단독 발화만으로는 위양성 바닥이 너무 높다. 문말(C1)과
# 문두(C2) 두 자리에서 다 틀려야 발음 결함으로 볼 수 있고, 덤으로 위치에
# 따라만 무너지는 결함도 잡힌다.
