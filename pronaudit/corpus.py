"""검사 문항 생성.

원칙 하나: **실재하는 낱말만 쓴다.** STT는 언어모델을 품고 있어서 없는 말을
들으면 가장 가까운 실재 낱말로 고쳐 적는다. 무의미 음절을 넣으면 TTS가
제대로 읽어도 STT가 딴 말로 적고, 반대로 TTS가 뭉개도 STT가 원래 말로
복원해 버린다 — 어느 쪽이든 측정이 무의미해진다.

원칙 둘: **최소대립쌍으로 짠다.** 자모 하나만 다른 두 실재 낱말을 나란히
돌리면, 한쪽이 다른 쪽으로 들리는 사건이 곧 그 자모 대립이 무너졌다는
증거가 된다. 그냥 문장을 많이 돌리는 것보다 규칙이 훨씬 빨리 드러난다.
"""
